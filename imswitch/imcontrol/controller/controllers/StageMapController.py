    @APIExport()
    def getStageMapTiles(self, fromId: int = 0, includePreviews: bool = True) -> Dict:
        """Return tile metadata (and previews) so the frontend can rebuild the map."""
        with self._tilesLock:
            tiles = []
            for tile in self._tiles:
                if tile["id"] < fromId:
                    continue
                entry = {
                    "id": tile["id"],
                    "x": tile["x"],
                    "y": tile["y"],
                    "widthUm": tile["widthUm"],
                    "heightUm": tile["heightUm"],
                    "channel": tile["channel"],
                    "timestamp": tile["timestamp"],
                }
                if includePreviews:
                    entry["image"] = tile["preview"]
                    entry["format"] = "jpeg"
                tiles.append(entry)
        return {"tiles": tiles, "sessionPath": self._sessionPath or ""}

    @APIExport()
    def gotoStagePosition(self, x: float, y: float, isAbsolute: bool = True,
                          isBlocking: bool = False) -> bool:
        """Move the XY stage (used for map double-click / arrow-key navigation).

        With isBlocking=True the call returns only after the move finished, so
        the caller can immediately snap a tile at the settled position.
        """
        if self._stage is None:
            return False
        try:
            self._stage.move((float(x), float(y)), "XY", is_absolute=isAbsolute,
                             is_blocking=isBlocking)
            return True
        except Exception as e:
            self._logger.error(f"Could not move stage: {e}")
            return False

    @APIExport()
    def saveStitchedOmeTiff(self, filename: str = "") -> Dict:
        """Fuse all raw tiles into a multi-channel stitched OME-TIFF.

        Tiles are placed on a common canvas in stage coordinates
        (last-written-wins in overlap regions). One OME channel per
        illumination channel. Returns the file path.
        """
        if not HAS_TIFFFILE:
            return {"success": False, "error": "tifffile not available"}
        if not self._sessionPath:
            return {"success": False, "error": "No active session"}

        with self._tilesLock:
            tiles = [t for t in self._tiles if t.get("rawPath") and os.path.exists(t["rawPath"])]
        if not tiles:
            return {"success": False, "error": "No raw tiles stored (enable saveRawTiles)"}

        pixelSize = self._getPixelSizeUm()
        channels = sorted({t["channel"] for t in tiles})

        # Canvas extent in stage coordinates (tile x/y is the FOV centre)
        minX = min(t["x"] - t["widthUm"] / 2 for t in tiles)
        maxX = max(t["x"] + t["widthUm"] / 2 for t in tiles)
        minY = min(t["y"] - t["heightUm"] / 2 for t in tiles)
        maxY = max(t["y"] + t["heightUm"] / 2 for t in tiles)
        canvasW = int(np.ceil((maxX - minX) / pixelSize))
        canvasH = int(np.ceil((maxY - minY) / pixelSize))

        if canvasW <= 0 or canvasH <= 0:
            return {"success": False, "error": "Empty canvas extent"}
        if float(canvasW) * canvasH * len(channels) > self.MAX_STITCH_PIXELS:
            return {
                "success": False,
                "error": f"Stitched canvas too large ({canvasW}x{canvasH}x{len(channels)} px). "
                         f"Reduce the mapped area or number of channels.",
            }

        # Determine dtype from the first tile
        firstFrame = tifffile.imread(tiles[0]["rawPath"])
        dtype = firstFrame.dtype
        isColor = firstFrame.ndim == 3

        try:
            if isColor:
                # colour cameras: stitch as RGB, ignore channel separation
                canvas = np.zeros((canvasH, canvasW, firstFrame.shape[2]), dtype=dtype)
                stack = None
            else:
                stack = np.zeros((len(channels), canvasH, canvasW), dtype=dtype)
                canvas = None
        except MemoryError:
            return {"success": False, "error": "Not enough memory for stitched canvas"}

        for tile in tiles:
            try:
                frame = tifffile.imread(tile["rawPath"])
            except Exception as e:
                self._logger.warning(f"Skipping unreadable tile {tile['rawPath']}: {e}")
                continue
            h, w = frame.shape[0], frame.shape[1]
            # top-left pixel of this tile on the canvas
            px = int(round((tile["x"] - tile["widthUm"] / 2 - minX) / pixelSize))
            py = int(round((tile["y"] - tile["heightUm"] / 2 - minY) / pixelSize))
            px0, py0 = max(0, px), max(0, py)
            px1, py1 = min(canvasW, px + w), min(canvasH, py + h)
            if px1 <= px0 or py1 <= py0:
                continue
            fx0, fy0 = px0 - px, py0 - py
            if isColor:
                canvas[py0:py1, px0:px1, :] = frame[fy0:fy0 + (py1 - py0), fx0:fx0 + (px1 - px0), :]
            else:
                ci = channels.index(tile["channel"])
                stack[ci, py0:py1, px0:px1] = frame[fy0:fy0 + (py1 - py0), fx0:fx0 + (px1 - px0)]

        if not filename:
            filename = datetime.now().strftime("stagemap_stitched_%Y%m%d_%H%M%S.ome.tif")
        if not filename.endswith((".ome.tif", ".ome.tiff")):
            filename += ".ome.tif"
        outPath = os.path.join(self._sessionPath, filename)

        try:
            if isColor:
                tifffile.imwrite(
                    outPath, canvas, ome=True,
                    metadata={
                        "axes": "YXS",
                        "PhysicalSizeX": pixelSize, "PhysicalSizeXUnit": "µm",
                        "PhysicalSizeY": pixelSize, "PhysicalSizeYUnit": "µm",
                    },
                )
            else:
                tifffile.imwrite(
                    outPath, stack, ome=True,
                    metadata={
                        "axes": "CYX",
                        "Channel": {"Name": channels},
                        "PhysicalSizeX": pixelSize, "PhysicalSizeXUnit": "µm",
                        "PhysicalSizeY": pixelSize, "PhysicalSizeYUnit": "µm",
                    },
                )
        except Exception as e:
            self._logger.error(f"Could not write stitched OME-TIFF: {e}")
            return {"success": False, "error": str(e)}

        self._logger.info(f"Stitched OME-TIFF written to {outPath}")
        return {
            "success": True,
            "path": outPath,
            "widthPx": canvasW,
            "heightPx": canvasH,
            "channels": channels,
        }

